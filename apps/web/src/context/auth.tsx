import { createContext, createSignal, useContext, type Accessor, type JSX } from 'solid-js';
import type { Session, User } from '@supabase/supabase-js';
import { assert } from '@/utils';

type OAuthProvider = 'google' | 'apple' | 'github';
export type LocalProfile = { displayName: string; avatarDataUrl?: string };
const PROFILE_KEY = 'syka.local-profile.v1';
const LOCAL_ONLY_MESSAGE = 'Syka runs locally and does not use a Diffusion account.';

function normalizedAvatar(value: unknown): string | undefined {
  // Only the compact raster generated by Syka belongs in a local preference.
  // Never render a remote URL, an SVG or arbitrarily large legacy data.
  if (typeof value !== 'string' || value.length > 270_000) return undefined;
  return /^data:image\/webp;base64,[A-Za-z0-9+/]+={0,2}$/.test(value) ? value : undefined;
}

type AuthContextValue = {
  localProfile: Accessor<LocalProfile>;
  updateLocalProfile: (profile: LocalProfile) => void;
  // Compatibility with cloud consumers: local access is not a cloud session.
  session: Accessor<Session | null>;
  user: Accessor<User | null>;
  isAuthenticated: Accessor<boolean>;
  isLoading: Accessor<boolean>;
  accessLevel: Accessor<number>;
  remainingCredits: Accessor<number>;
  creditLimit: Accessor<number>;
  nextCreditReset: Accessor<Date | null>;
  isPro: Accessor<boolean>;
  hasStripeCustomer: Accessor<boolean>;
  productUpdatesEnabled: Accessor<boolean>;
  marketingAnnouncementsEnabled: Accessor<boolean>;
  signInWithOAuth: (provider: OAuthProvider) => Promise<void>;
  signInWithOtp: (email: string) => Promise<{ error: string | null }>;
  signOut: () => Promise<void>;
  deleteAccount: () => Promise<{ error: string | null }>;
  refreshSession: () => Promise<void>;
};

const AuthContext = createContext<AuthContextValue>();

function readLocalProfile(): LocalProfile {
  try {
    const value: unknown = JSON.parse(localStorage.getItem(PROFILE_KEY) ?? 'null');
    if (value && typeof value === 'object' && 'displayName' in value && typeof value.displayName === 'string') {
      return {
        displayName: value.displayName.trim().slice(0, 80) || 'Syka',
        avatarDataUrl: normalizedAvatar('avatarDataUrl' in value ? value.avatarDataUrl : undefined),
      };
    }
  } catch {
    // A damaged or unavailable preference must not prevent opening projects.
  }
  return { displayName: 'Syka' };
}

export function AuthProvider(props: { children: JSX.Element }) {
  const [localProfile, setLocalProfile] = createSignal(readLocalProfile());
  const updateLocalProfile = (profile: LocalProfile) => {
    const avatarDataUrl = normalizedAvatar(profile.avatarDataUrl);
    if (profile.avatarDataUrl !== undefined && !avatarDataUrl) {
      throw new Error('The profile photo is invalid. Choose another image.');
    }
    const next: LocalProfile = {
      displayName: profile.displayName.trim().slice(0, 80) || 'Syka',
      avatarDataUrl,
    };
    localStorage.setItem(PROFILE_KEY, JSON.stringify(next));
    setLocalProfile(next);
  };

  const ctx: AuthContextValue = {
    localProfile,
    updateLocalProfile,
    session: () => null,
    user: () => null,
    isAuthenticated: () => false,
    isLoading: () => false,
    accessLevel: () => 0,
    remainingCredits: () => 0,
    creditLimit: () => 0,
    nextCreditReset: () => null,
    isPro: () => false,
    hasStripeCustomer: () => false,
    productUpdatesEnabled: () => false,
    marketingAnnouncementsEnabled: () => false,
    async signInWithOAuth() { throw new Error(LOCAL_ONLY_MESSAGE); },
    async signInWithOtp() { return { error: LOCAL_ONLY_MESSAGE }; },
    async signOut() {},
    async deleteAccount() { return { error: LOCAL_ONLY_MESSAGE }; },
    async refreshSession() {},
  };

  return <AuthContext.Provider value={ctx}>{props.children}</AuthContext.Provider>;
}

export function useAuth(): AuthContextValue {
  const ctx = useContext(AuthContext);
  assert(ctx, 'useAuth must be used within AuthProvider');
  return ctx;
}
