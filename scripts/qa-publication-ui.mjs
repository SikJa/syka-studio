import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.SYKA_PLAYWRIGHT_PATH || 'playwright');
const output = resolve('.runtime/publication/qa');
await mkdir(output, { recursive: true });
const browser = await chromium.connectOverCDP('http://127.0.0.1:9338');
const page = browser.contexts().flatMap(c => c.pages()).find(p => p.url().includes('5298'));
if (!page) throw Error('No se encontró la ventana de publicación.');
const errors = [];
page.on('pageerror', e => errors.push(e.message));
await page.goto('http://localhost:5298/#/?dashboard=zernio');
await page.getByText('Todavía no agregaste una conexión.').waitFor();
await page.getByRole('button', { name: 'API key', exact: true }).click();
await page.getByLabel('Nombre de la conexión').fill('Prueba local A');
await page.getByLabel('API key de Zernio', { exact: true }).fill(`sk_${'d'.repeat(64)}`);
await page.getByRole('button', { name: 'Guardar conexión', exact: true }).click();
await page.getByText('Prueba local A', { exact: true }).waitFor();
if (await page.getByLabel('API key de Zernio', { exact: true }).inputValue()) throw Error('La clave quedó visible en el formulario.');
await page.screenshot({ path: resolve(output, 'settings-key-local.png') });
await page.getByRole('button', { name: 'Quitar', exact: true }).click();
await page.getByRole('button', { name: 'Quitar conexión', exact: true }).click();
await page.getByText('Todavía no agregaste una conexión.').waitFor();
await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
await page.screenshot({ path: resolve(output, 'settings-oauth.png') });
await page.goto('http://localhost:5298/#/?dashboard=publication');
await page.getByText('Todavía no hay borradores', { exact: true }).waitFor();
await page.screenshot({ path: resolve(output, 'drafts-empty.png') });
await page.emulateMedia({ reducedMotion: 'reduce' });
await page.goto('http://localhost:5298/#/?dashboard=zernio');
await page.getByRole('button', { name: 'API key', exact: true }).click();
const duration = await page.locator('.t-panel-slide').evaluate(el => getComputedStyle(el).transitionDuration);
if (duration !== '0s') throw Error('La transición no respeta movimiento reducido.');
await page.emulateMedia({ reducedMotion: 'no-preference' });
await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
await writeFile(resolve(output, 'ui-verification.json'), JSON.stringify({ desktop: await page.evaluate(() => !!window.desktop), keyInputCleared: true, connectionRemoved: true, reducedMotion: duration, errors, url: page.url() }, null, 2));
console.log(JSON.stringify({ checks: 5, errors, screenshots: output }));
await browser.close();
