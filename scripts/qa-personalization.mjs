import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { contrast } from '../apps/web/src/lib/appearance/color.ts';
const require = createRequire(resolve('.runtime/personalization/package.json'));
const { chromium } = require('playwright');
const output = resolve('output/personalization'); await mkdir(output, {recursive:true});
const browser = await chromium.launch({ channel:'chrome', headless:true });
const context = await browser.newContext({ viewport:{width:1100,height:820}, permissions:['clipboard-read','clipboard-write'] });
const page = await context.newPage();
const errors = []; page.on('pageerror', e => errors.push(e.message));
const url = 'http://127.0.0.1:5396/personalization-preview.html';
const results = [];
const record = (name, data = {}) => results.push({name, ...data});
const trigger = () => page.getByRole('button', {name:'Elegir color de acento'});
const open = async () => { await trigger().click(); await page.getByLabel('Valor del color').waitFor(); await page.waitForTimeout(220); };
const apply = async () => { await page.getByRole('button',{name:'Aplicar color'}).click(); await page.locator('.syka-color-popover').waitFor({state:'hidden'}); };
const color = async () => (await trigger().innerText()).trim();
const tokens = () => page.evaluate(() => {
  const s = getComputedStyle(document.documentElement);
  return Object.fromEntries(['--primary','--primary-foreground','--primary-hover','--primary-pressing','--selection','--selection-foreground','--ring','--destructive','--meter-green'].map(k=>[k,s.getPropertyValue(k).trim()]));
});
try {
  await page.goto(url); await trigger().waitFor();
  const baseline = await tokens();
  await open(); await page.getByRole('button',{name:'Lavanda',exact:true}).click();
  assert.equal(await color(),'#A78BFA');
  await page.screenshot({path:resolve(output,'dark-picker.png')});
  await apply(); await page.reload(); assert.equal(await color(),'#A78BFA'); record('preset, apply, reload persisted');
  await open(); await page.getByRole('button',{name:'Menta',exact:true}).click();
  await page.keyboard.press('Escape'); await page.locator('.syka-color-popover').waitFor({state:'hidden'});
  assert.equal(await color(),'#A78BFA'); assert.equal(await trigger().evaluate(el=>el===document.activeElement),true); record('Escape cancels and restores trigger focus');
  await open(); await page.getByLabel('Valor del color').fill('url(https://invalid)');
  assert.equal(await page.getByRole('button',{name:'Aplicar color'}).isEnabled(),false); assert.equal(await color(),'#A78BFA');
  assert.ok(await page.getByRole('alert').isVisible()); await page.screenshot({path:resolve(output,'invalid-input.png')});
  await page.getByRole('button',{name:'Lavanda',exact:true}).click(); assert.equal(await page.getByRole('button',{name:'Aplicar color'}).isEnabled(),true);
  await page.getByLabel('Valor del color').fill(''); await page.getByLabel('Valor del color').pressSequentially('#123456');
  assert.equal(await page.getByLabel('Valor del color').inputValue(),'#123456'); assert.equal(await color(),'#123456'); record('invalid input rejected, same preset recovers, full HEX typing preserved');
  await page.getByRole('button',{name:'Cancelar',exact:true}).click(); assert.equal(await color(),'#A78BFA');
  for (const value of ['#FFFFFF','#000000','#FFFF00','#FF0000','#68C6AC','#FFFFFF00']) {
    await open(); await page.getByLabel('Valor del color').fill(value); await apply();
    for (const theme of ['dark','light']) {
      if (await page.locator('html').getAttribute('data-kb-theme') !== theme) await page.getByRole('button',{name:'Cambiar tema'}).click();
      await page.waitForTimeout(250); const t = await tokens();
      assert.ok(contrast(t['--primary'],t['--primary-foreground']) >= 4.5);
      assert.ok(contrast(t['--selection'],t['--selection-foreground']) >= 4.5);
      const button = await page.getByRole('button',{name:'Botón principal'}).evaluate(el=>{const s=getComputedStyle(el);return {background:s.backgroundColor,foreground:s.color};});
      assert.ok(contrast(button.background,button.foreground)>=4.5);
      const fill = await page.locator('[data-slot="slider-fill"]').evaluate(el=>getComputedStyle(el).backgroundColor);
      assert.ok(contrast(fill,theme==='dark'?'#171717':'#FFFFFF')>=3);
      await page.getByRole('button',{name:'Botón principal'}).hover(); await page.waitForTimeout(200);
      const hovered = await page.getByRole('button',{name:'Botón principal'}).evaluate(el=>{const s=getComputedStyle(el);return {background:s.backgroundColor,foreground:s.color};});
      assert.ok(contrast(hovered.background,hovered.foreground)>=4.5);
      await page.mouse.move(1,1);
      assert.equal(t['--destructive'],baseline['--destructive']); assert.equal(t['--meter-green'],baseline['--meter-green']);
      record('real CSS contrast and semantic isolation',{value,theme,contrast:contrast(button.background,button.foreground)});
    }
  }
  await open(); await page.getByRole('button',{name:'Menta',exact:true}).click();
  await page.getByRole('button',{name:'RGB',exact:true}).click(); assert.match(await page.getByLabel('Valor del color').inputValue(),/^rgb\(/);
  await page.getByRole('button',{name:'OKLCH',exact:true}).click(); assert.match(await page.getByLabel('Valor del color').inputValue(),/^oklch\(/);
  await page.getByRole('button',{name:'Copiar color',exact:true}).click();
  assert.match(await page.evaluate(()=>navigator.clipboard.readText()),/^oklch\(/); record('format switch and clipboard');
  await page.getByRole('button',{name:'HEX',exact:true}).click();
  const before = await color(); await page.getByRole('group',{name:'Saturación y brillo',exact:true}).press('ArrowLeft'); assert.notEqual(await color(), before);
  await page.getByRole('slider',{name:'Tono',exact:true}).press('ArrowRight');
  const bounds = await page.locator('.syka-color-plane').boundingBox();
  await page.mouse.move(bounds.x + 20,bounds.y + 20); await page.mouse.down(); await page.mouse.move(bounds.x + bounds.width * .5,bounds.y + bounds.height * .45); await page.mouse.up();
  await page.getByRole('slider',{name:'Opacidad',exact:true}).press('ArrowLeft'); record('keyboard plane, hue, opacity and real pointer drag');
  await page.screenshot({path:resolve(output,'light-picker.png')}); await apply();
  await page.getByRole('button',{name:'Restaurar azul original'}).click(); await page.reload(); assert.equal(await color(),'#008CFF'); record('restore default persisted');
  await page.setViewportSize({width:360,height:640}); await open();
  const box = await page.locator('.syka-color-popover').boundingBox();
  assert.ok(box.x>=0 && box.x+box.width<=360 && box.y>=0 && box.y+box.height<=641,JSON.stringify(box));
  await page.getByRole('button',{name:'Aplicar color'}).scrollIntoViewIfNeeded(); await page.screenshot({path:resolve(output,'narrow-picker.png')}); record('360x640 portal containment',{box});
  await page.keyboard.press('Escape');
  await context.addInitScript(() => { localStorage.setItem('syka.appearance.v1','{invalid'); Object.defineProperty(window,'EyeDropper',{value:undefined,configurable:true}); });
  await page.reload(); assert.equal(await color(),'#008CFF'); await open(); assert.equal(await page.getByRole('button',{name:'Tomar color de pantalla'}).count(),0); record('corrupt storage fallback; unavailable eyedropper hidden');
  await page.keyboard.press('Escape');
  const denied = await browser.newContext({viewport:{width:900,height:700},reducedMotion:'reduce'});
  await denied.addInitScript(()=>{ Object.defineProperty(window,'localStorage',{get(){throw new Error('storage disabled');}}); });
  const deniedPage = await denied.newPage(); await deniedPage.goto(url); await deniedPage.getByRole('button',{name:'Elegir color de acento'}).click();
  await deniedPage.getByRole('button',{name:'Menta',exact:true}).click(); await deniedPage.getByRole('button',{name:'Aplicar color'}).click();
  assert.ok(await deniedPage.getByText('El color está aplicado por esta sesión.',{exact:false}).isVisible());
  await deniedPage.reload(); assert.ok((await deniedPage.getByRole('button',{name:'Elegir color de acento'}).innerText()).includes('#008CFF'));
  await deniedPage.getByRole('button',{name:'Elegir color de acento'}).click();
  assert.equal(await deniedPage.locator('.syka-color-popover').evaluate(el=>getComputedStyle(el).animationName),'none'); record('denied storage: session-only warning and reload fallback; reduced motion');
  await denied.close(); assert.deepEqual(errors,[]);
  await writeFile(resolve(output,'results.json'),JSON.stringify({passed:true,results,errors},null,2));
  console.log(JSON.stringify({passed:true,checks:results.length,output},null,2));
} finally { await browser.close(); }
