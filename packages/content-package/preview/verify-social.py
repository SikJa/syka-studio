"""Isolated onboarding + per-account browser verification. Uses port 5307, not the user's preview."""
from pathlib import Path
import json
from playwright.sync_api import sync_playwright, expect

root = Path(__file__).resolve().parents[3] / '.runtime' / 'content-package-qa'
out = root / 'qa'
out.mkdir(parents=True, exist_ok=True)
base = 'http://127.0.0.1:5307'
with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, channel='chrome')
    page = browser.new_page(viewport={'width': 1440, 'height': 1000}, reduced_motion='reduce')
    errors, console = [], []
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.on('console', lambda m: console.append(m.text) if m.type == 'error' else None)
    page.goto(base); page.wait_for_load_state('networkidle')
    expect(page.locator('#question')).to_contain_text('Primero')
    page.screenshot(path=str(out / '01-onboarding.png'), full_page=True)
    # Empty means no accounts, not invented connections.
    page.locator('#nav-content').click()
    expect(page.locator('#no-accounts')).to_be_visible()
    page.locator('#demo-accounts').click()
    expect(page.locator('#demo-banner')).to_be_visible()
    page.locator('#nav-style').click()
    page.locator('#style-name').fill('Marca de ensayo QA')
    page.locator('#answer').fill('Comparto procesos de edición para creadores.')
    page.locator('#add-reference').click()
    page.locator('[data-kind="image"]').click()
    page.locator('#ref-label').fill('Encuadre de mi video')
    page.locator('#ref-file').set_input_files(str(root / 'frame.png'))
    page.locator('#ref-purpose').select_option('cover')
    page.locator('#ref-note').fill('Me gusta conservar la cara y dejar aire para el título.')
    page.get_by_role('button', name='Guardar referencia', exact=True).click()
    expect(page.locator('#reference-dialog')).not_to_be_visible()
    expect(page.locator('.reference-card')).to_have_count(1)
    page.locator('#add-reference').click()
    page.locator('[data-kind="text"]').click()
    page.locator('#ref-label').fill('Descripción anterior')
    page.locator('#ref-text').fill('Así preparo una edición. Mirá los pasos del video.')
    page.locator('#ref-note').fill('El tono cercano y la frase corta.')
    page.locator('#ref-purpose').select_option('description')
    page.get_by_role('button', name='Guardar referencia', exact=True).click()
    expect(page.locator('.reference-card')).to_have_count(2)
    page.locator('#add-reference').click()
    page.locator('#ref-label').fill('Referencia externa de ejemplo')
    page.locator('#ref-url').fill('https://example.com/inspiration')
    page.locator('#ref-origin').select_option('inspiration')
    page.locator('#ref-note').fill('Guardado como referencia; no abrir ni analizar durante QA.')
    page.get_by_role('button', name='Guardar referencia', exact=True).click()
    expect(page.locator('.reference-card')).to_have_count(3)
    page.locator('#next-step').click()
    expect(page.locator('#question')).to_contain_text('sonar')
    page.locator('#answer').fill('Cercano y directo. Sin promesas comerciales.')
    page.screenshot(path=str(out / '02-references.png'), full_page=True)
    page.locator('#next-step').click()
    expect(page.locator('#question')).to_contain_text('descripciones')
    page.locator('#answer').fill('Contexto breve del video. Sin hashtags automáticos.')
    page.locator('#next-step').click()
    expect(page.locator('#question')).to_contain_text('portada')
    page.locator('#answer').fill('Mi cara, texto corto y colores sobrios.')
    page.locator('#next-step').click()
    expect(page.locator('#question')).to_contain_text('todas tus redes')
    page.locator('#answer').fill('TikTok más corto que Instagram.')
    page.get_by_label('Extensión para TikTok').select_option('direct')
    page.get_by_label('Indicaciones para Instagram').fill('Dar contexto en dos párrafos.')
    page.locator('#next-step').click()
    expect(page.locator('#content-view')).to_be_visible()
    page.locator('#prepare-social').click()
    expect(page.locator('#delivery')).to_be_visible()
    package = page.request.get(base + '/api/session?demo=1').json()['pkg']
    image_ref = next(ref for ref in package['social']['styleSnapshot']['references'] if ref['kind'] == 'image')
    assert (root / 'packages' / package['id'] / image_ref['file']).is_file()
    ig_text = page.locator('#target-description').input_value()
    page.locator('#target-description').fill('Descripción propia para Instagram QA')
    page.locator('[data-account="demo-tiktok"]').click()
    assert page.locator('#target-description').input_value() != ig_text
    page.locator('#target-description').fill('Versión breve de TikTok QA')
    page.locator('#review-target').click()
    expect(page.locator('#target-state')).to_have_text('Revisado')
    page.locator('[data-account="demo-instagram"]').click()
    expect(page.locator('#target-description')).to_have_value('Descripción propia para Instagram QA')
    page.locator('#review-target').click()
    expect(page.locator('#handoff')).to_be_enabled()
    page.evaluate('window.scrollTo(0, 0)')
    page.screenshot(path=str(out / '03-instagram.png'), full_page=True)
    page.locator('[data-account="demo-tiktok"]').click()
    page.screenshot(path=str(out / '04-tiktok.png'), full_page=True)
    page.locator('#handoff').click()
    expect(page.locator('#download')).to_be_visible()
    # Reload preserves reusable style and per-platform content.
    page.reload(); page.wait_for_load_state('networkidle')
    page.locator('#nav-content').click()
    page.locator('[data-account="demo-tiktok"]').click()
    expect(page.locator('#target-description')).to_have_value('Versión breve de TikTok QA')
    # Changing the profile blocks old approvals, even when all target texts were reviewed.
    page.locator('#nav-style').click()
    page.locator('#answer').fill('Otro público, otra dirección.')
    page.locator('#next-step').click()
    expect(page.locator('#question')).to_contain_text('sonar')
    page.locator('#nav-content').click()
    expect(page.locator('#handoff')).to_be_disabled()
    expect(page.locator('#target-state')).to_contain_text('cambiaron')
    page.set_viewport_size({'width': 390, 'height': 844})
    page.screenshot(path=str(out / '05-mobile.png'), full_page=True)
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    page.locator('#nav-style').click()
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    assert not errors, errors
    csp_errors = [x for x in console if 'Content Security Policy' in x or 'Refused' in x]
    assert not csp_errors, csp_errors
    (out / 'result.json').write_text(json.dumps({'pageErrors': errors, 'console': console, 'checks': ['empty-accounts', 'explicit-demo', 'guided-style', 'image-reference-upload', 'text-reference', 'url-reference-no-fetch', 'portable-style-images', 'per-platform-preferences', 'independent-account-drafts', 'unsaved-switch-preserves-draft', 'per-account-review', 'reviewed-multiplatform-handoff', 'reload-persistence', 'style-change-invalidates', 'mobile-no-overflow', 'reduced-motion'], 'accountSource': 'demo'}, indent=2))
    browser.close()
